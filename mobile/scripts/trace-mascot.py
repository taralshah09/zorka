# Traces the flat tiger mascot PNG into the SVG paths the animated <Mascot /> draws
# (src/core/ui/mascot/tigerPaths.generated.ts). The eyes are cut out of the face so they can be redrawn and animated
# (blink, eye-roll); every other shape is traced 1:1 from the artwork.
#
# Run: python scripts/trace-mascot.py ../.temp/mascot-logos/03-tiger.png
import sys
from pathlib import Path

import cv2
import numpy as np

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "../.temp/mascot-logos/03-tiger.png")
OUT = Path(__file__).resolve().parent.parent / "src" / "core" / "ui" / "mascot" / "tigerPaths.generated.ts"

PALETTE = {
    "ink": (21, 22, 25),
    "lime": (216, 237, 98),
    "cream": (249, 244, 235),
    "lilac": (180, 158, 251),
}


def classify(rgba: np.ndarray) -> dict[str, np.ndarray]:
    rgb = rgba[..., :3].astype(np.int32)
    inside = rgba[..., 3] > 127
    names = list(PALETTE)
    dist = np.stack([((rgb - np.array(PALETTE[n])) ** 2).sum(-1) for n in names], -1)
    nearest = dist.argmin(-1)
    return {n: (inside & (nearest == i)).astype(np.uint8) * 255 for i, n in enumerate(names)} | {
        "silhouette": inside.astype(np.uint8) * 255
    }


def clean(mask: np.ndarray, k: int = 3) -> np.ndarray:
    kernel = np.ones((k, k), np.uint8)
    return cv2.morphologyEx(cv2.morphologyEx(mask, cv2.MORPH_OPEN, kernel), cv2.MORPH_CLOSE, kernel)


def path_of(contours, min_area: float = 80.0, eps: float = 1.6) -> str:
    """Closed, smoothed path: polygon simplified, then quadratic curves through edge midpoints."""
    parts = []
    for c in contours:
        if cv2.contourArea(c) < min_area:
            continue
        pts = cv2.approxPolyDP(c, eps, True).reshape(-1, 2).astype(float)
        if len(pts) < 3:
            continue
        mids = (pts + np.roll(pts, -1, axis=0)) / 2
        d = [f"M{mids[-1][0]:.0f} {mids[-1][1]:.0f}"]
        for p, m in zip(pts, mids):
            d.append(f"Q{p[0]:.0f} {p[1]:.0f} {m[0]:.0f} {m[1]:.0f}")
        parts.append("".join(d) + "Z")
    return "".join(parts)


def main() -> None:
    rgba = cv2.cvtColor(cv2.imread(str(SRC), cv2.IMREAD_UNCHANGED), cv2.COLOR_BGRA2RGBA)
    m = classify(rgba)
    ink, lime, cream, lilac, sil = (clean(m[k]) for k in ("ink", "lime", "cream", "lilac", "silhouette"))

    # Eyes: the two ink blobs that hold a cream catch-light, in the upper-middle of the face.
    n, labels, stats, cent = cv2.connectedComponentsWithStats(ink)
    h, w = ink.shape
    eyes = []
    for i in range(1, n):
        x, y, bw, bh, area = stats[i]
        cx, cy = cent[i]
        if not (0.25 * h < cy < 0.6 * h and 2000 < area < 40000 and 0.6 < bw / bh < 1.6):
            continue
        # A real eye holds a cream catch-light inside its box (the forehead stripes don't).
        if cream[y : y + bh, x : x + bw].sum() / 255 > 300:
            eyes.append((i, x, y, bw, bh, cx, cy))
    eyes.sort(key=lambda e: e[5])
    if len(eyes) != 2:
        raise SystemExit(f"expected 2 eyes, found {len(eyes)}")

    eye_mask = np.zeros_like(ink)
    eye_geo = []
    for i, x, y, bw, bh, cx, cy in eyes:
        blob = (labels == i).astype(np.uint8) * 255
        # Fill the catch-light hole so the socket is one solid shape.
        cs, _ = cv2.findContours(blob, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        solid = np.zeros_like(blob)
        cv2.drawContours(solid, cs, -1, 255, -1)
        # The lash arc is joined to the eye by a thin stroke: open with a big round kernel to keep only the eyeball.
        core = cv2.morphologyEx(solid, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (41, 41)))
        k, lab, st, _ = cv2.connectedComponentsWithStats(core)
        core = (lab == 1 + int(np.argmax(st[1:, 4]))).astype(np.uint8) * 255
        eye_mask |= core
        cs, _ = cv2.findContours(core, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        (ex, ey), (ew, eh), ang = cv2.fitEllipse(max(cs, key=cv2.contourArea))
        eye_geo.append({"cx": round(ex), "cy": round(ey), "rx": round(min(ew, eh) / 2), "ry": round(max(ew, eh) / 2),
                        "path": path_of(cs)})

    # Face colour layers; cream catch-lights inside the eyes are dropped (the animated eye draws its own).
    cream_face = cream & ~cv2.dilate(eye_mask, np.ones((31, 31), np.uint8))
    lime_and_eyes = lime | eye_mask  # face fill runs under the sockets, so a closing lid shows lime

    def layer(mask: np.ndarray, mode=cv2.RETR_CCOMP, min_area=80.0) -> str:
        cs, _ = cv2.findContours(mask, mode, cv2.CHAIN_APPROX_NONE)
        return path_of(cs, min_area)

    ys, xs = np.nonzero(sil)
    box = (int(xs.min()) - 24, int(ys.min()) - 24, int(xs.max() - xs.min()) + 48, int(ys.max() - ys.min()) + 48)

    # Lime fill with ink holes (stripes, brows, nose, mouth). evenodd fill keeps the holes open.
    out = [
        "// Generated by scripts/trace-mascot.py from the 03-tiger mascot artwork. Do not edit by hand.",
        "// Coordinates are in the source PNG's pixel space; use VIEWBOX to frame them.",
        f'export const VIEWBOX = "{box[0]} {box[1]} {box[2]} {box[3]}";',
        f"export const BOX = {{ x: {box[0]}, y: {box[1]}, w: {box[2]}, h: {box[3]} }} as const;",
        f'export const SILHOUETTE = "{layer(sil, cv2.RETR_EXTERNAL)}";',
        f'export const FACE = "{layer(lime_and_eyes)}";',
        f'export const FACE_OUTER = "{layer(lime_and_eyes, cv2.RETR_EXTERNAL, 4000)}";',
        f'export const MUZZLE = "{layer(cream_face)}";',
        f'export const EARS = "{layer(lilac)}";',
        "export const EYES = [",
        *[
            f'  {{ cx: {e["cx"]}, cy: {e["cy"]}, rx: {e["rx"]}, ry: {e["ry"]}, path: "{e["path"]}" }},'
            for e in eye_geo
        ],
        "] as const;",
        "",
    ]
    # Nose: the ink blob just below the eyes in the centre — used to place the glossy highlight.
    for i in range(1, n):
        x, y, bw, bh, area = stats[i]
        cx, cy = cent[i]
        if abs(cx - w / 2) < 0.08 * w and 0.55 * h < cy < 0.75 * h and area > 4000:
            out.insert(-1, f"export const NOSE = {{ cx: {cx:.0f}, cy: {y + bh * 0.3:.0f}, w: {bw}, h: {bh} }} as const;")
            break
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes); eyes {[(e['cx'], e['cy'], e['rx'], e['ry']) for e in eye_geo]}")


if __name__ == "__main__":
    main()
