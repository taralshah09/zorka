// Generates the Zorka bubble's tiger (modules/zorka-overlay/android/src/main/res/drawable/zorka_tiger.xml) from the
// traced mascot paths the app draws (src/core/ui/mascot/tigerPaths.generated.ts), so the bubble and the in-app tiger
// are the same artwork: extruded edge, ink outline, lime face, lilac ears, cream muzzle, eyes with pupils and glints.
// An Android vector drawable, flat (no gradients). Run: npm run gen:overlay-tiger
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "src", "core", "ui", "mascot", "tigerPaths.generated.ts"), "utf8");
const out = join(root, "modules", "zorka-overlay", "android", "src", "main", "res", "drawable", "zorka_tiger.xml");

const str = (name) => {
  const m = new RegExp(`export const ${name} =\\s*"([^"]+)"`).exec(src);
  if (!m) throw new Error(`${name} not found`);
  return m[1];
};
const box = /export const BOX = \{ x: (\d+), y: (\d+), w: (\d+), h: (\d+) \}/.exec(src);
if (!box) throw new Error("BOX not found");
const [x, y, w, h] = box.slice(1).map(Number);
const eyes = [...src.matchAll(/cx: (\d+),\s*cy: (\d+),\s*rx: (\d+),\s*ry: (\d+),\s*path: "([^"]+)"/g)].map((m) => ({
  cx: +m[1],
  cy: +m[2],
  rx: +m[3],
  ry: +m[4],
  path: m[5],
}));
const nose = /export const NOSE = \{ cx: (\d+), cy: (\d+)/.exec(src);

// Same colours as Mascot.tsx ART (brand art, not themed).
const ART = { ink: "#151619", edge: "#050607", lime: "#D8ED62", limeShade: "#9DB23A", cream: "#F9F4EB", lilac: "#B49EFB" };
const EXTRUDE = 26;
const ellipse = (cx, cy, rx, ry) => `M${cx - rx},${cy} a${rx},${ry} 0 1,0 ${2 * rx},0 a${rx},${ry} 0 1,0 ${-2 * rx},0 Z`;
const path = (d, fill, evenOdd = false) =>
  `    <path android:pathData="${d}" android:fillColor="${fill}"${evenOdd ? ' android:fillType="evenOdd"' : ""} />`;

const eyeXml = eyes
  .map((e, i) => {
    const side = i === 0 ? 1 : -1;
    const pr = { rx: e.rx * 1.05 + 3, ry: e.ry * 1.05 + 3 };
    return [
      "    <group>",
      `      <clip-path android:pathData="${e.path}" />`,
      `  ${path(e.path, ART.cream)}`,
      `  ${path(ellipse(e.cx, e.cy, pr.rx, pr.ry), ART.ink)}`,
      `  ${path(ellipse(e.cx + side * e.rx * 0.14, e.cy - e.ry * 0.28, e.rx * 0.32, e.rx * 0.32), ART.cream)}`,
      "    </group>",
      `    <path android:pathData="${e.path}" android:strokeColor="${ART.ink}" android:strokeWidth="6" />`,
    ].join("\n");
  })
  .join("\n");

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-overlay-tiger.mjs from tigerPaths.generated.ts. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp"
    android:height="${Math.round((48 * (h + EXTRUDE)) / w)}dp"
    android:viewportWidth="${w}"
    android:viewportHeight="${h + EXTRUDE}">
  <group android:translateX="${-x}" android:translateY="${-y}">
    <group android:translateY="${EXTRUDE}">
  ${path(str("SILHOUETTE"), ART.edge)}
    </group>
${path(str("SILHOUETTE"), ART.ink)}
${path(str("FACE"), ART.lime, true)}
${path(str("EARS"), ART.lilac, true)}
${path(str("MUZZLE"), ART.cream, true)}
${eyeXml}
${nose ? path(ellipse(+nose[1] - 28, +nose[2] - 14, 40, 13), "#73FFFFFF") : ""}
  </group>
</vector>
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, xml);
console.log(`wrote ${out} (${eyes.length} eyes)`);
