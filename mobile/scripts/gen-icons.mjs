// Brand name → file name, for symbols missing from this package version.
// Recorded in BRAND_GUIDELINES.md §5.
const ALIASES = {
  auto_awesome: "wand_stars",
  expand_more: "keyboard_arrow_down",
};

const pathsOf = (file) => {
  const svg = readFileSync(file, "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (viewBox !== "0 -960 960 960") throw new Error(`Unexpected viewBox in ${file}: ${viewBox}`);
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (d.length === 0) throw new Error(`No path in ${file}`);
  return d.join(" ");
};

const missing = [];
const entries = [];
for (const name of [...new Set(ICONS)]) {
  const file = ALIASES[name] ?? name;
  const outline = join(pkgDir, `${file}.svg`);
  const filled = join(pkgDir, `${file}-fill.svg`);
  if (!existsSync(outline)) {
    missing.push(name);
    continue;
  }
  const f0 = pathsOf(outline);
  const f1 = existsSync(filled) ? pathsOf(filled) : f0;
  entries.push(`  ${name}: [${JSON.stringify(f0)}, ${JSON.stringify(f1)}],`);
}

if (missing.length) {
  console.error(`Missing in @material-symbols/svg-400/rounded: ${missing.join(", ")}`);
  process.exit(1);
}

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/gen-icons.mjs. Do not edit by hand.
// Source: @material-symbols/svg-400 (Rounded, weight 400), Apache-2.0.
// Paths use viewBox "0 -960 960 960". Tuple = [FILL 0, FILL 1].
export const SYMBOLS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof SYMBOLS;
`,
);
console.log(`Wrote ${entries.length} icons to ${outFile}`);
